-- =====================================================================
--  Raccoon Lab - Base de datos normalizada (Firebird 5)
--  Igual que el proyecto del profe: llaves UUID con CHAR_TO_UUID/UUID_TO_CHAR
--  La matrícula NO es llave primaria: se puede editar sin romper relaciones
-- =====================================================================

-- ---------------------------------------------------------------------
--  CATÁLOGOS
-- ---------------------------------------------------------------------
CREATE TABLE ROLES (
    CLAVE        VARCHAR(10)  NOT NULL PRIMARY KEY,   -- ADMIN, PROFESOR, ALUMNO
    DESCRIPCION  VARCHAR(40)  NOT NULL,
    NIVEL        SMALLINT     NOT NULL                -- 3, 2, 1
);

CREATE TABLE TIPOS_USUARIO (
    CLAVE        VARCHAR(10)  NOT NULL PRIMARY KEY,   -- alumnos, maestros, admins
    DESCRIPCION  VARCHAR(40)  NOT NULL
);

-- Roles que recibe cada tipo de usuario al importarlo
CREATE TABLE TIPO_ROLES (
    TIPO  VARCHAR(10)  NOT NULL REFERENCES TIPOS_USUARIO (CLAVE),
    ROL   VARCHAR(10)  NOT NULL REFERENCES ROLES (CLAVE),
    PRIMARY KEY (TIPO, ROL)
);

CREATE TABLE CARRERAS (
    ID      CHAR(16) CHARACTER SET OCTETS  NOT NULL PRIMARY KEY,
    NOMBRE  VARCHAR(120)                   NOT NULL UNIQUE
);

-- ---------------------------------------------------------------------
--  GRUPOS Y USUARIOS
-- ---------------------------------------------------------------------
CREATE TABLE GRUPOS (
    ID          CHAR(16) CHARACTER SET OCTETS  NOT NULL PRIMARY KEY,
    CODIGO      VARCHAR(15)                    NOT NULL UNIQUE,   -- IRD-71
    ID_CARRERA  CHAR(16) CHARACTER SET OCTETS  REFERENCES CARRERAS (ID) ON DELETE SET NULL,
    CREADO      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE USUARIOS (
    ID             CHAR(16) CHARACTER SET OCTETS  NOT NULL PRIMARY KEY,
    MATRICULA      VARCHAR(20)                    NOT NULL UNIQUE,   -- es el login
    NOMBRE         VARCHAR(120)                   NOT NULL,
    PASSWORD       VARCHAR(100)                   NOT NULL,          -- hash bcrypt
    TIPO           VARCHAR(10)                    NOT NULL REFERENCES TIPOS_USUARIO (CLAVE),
    ID_GRUPO       CHAR(16) CHARACTER SET OCTETS  REFERENCES GRUPOS (ID) ON DELETE SET NULL,
    ACTIVO         BOOLEAN   DEFAULT TRUE              NOT NULL,
    CREADO         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ULTIMO_ACCESO  TIMESTAMP
);

CREATE TABLE USUARIO_ROLES (
    ID_USUARIO  CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES USUARIOS (ID) ON DELETE CASCADE,
    ROL         VARCHAR(10)                    NOT NULL REFERENCES ROLES (CLAVE),
    PRIMARY KEY (ID_USUARIO, ROL)
);

-- Maestros asignados a cada grupo
CREATE TABLE GRUPO_DOCENTES (
    ID_GRUPO    CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES GRUPOS (ID) ON DELETE CASCADE,
    ID_USUARIO  CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES USUARIOS (ID) ON DELETE CASCADE,
    PRIMARY KEY (ID_GRUPO, ID_USUARIO)
);

-- Bloqueo por intentos fallidos del login
CREATE TABLE INTENTOS_LOGIN (
    MATRICULA        VARCHAR(20)  NOT NULL PRIMARY KEY,
    FALLOS           SMALLINT     DEFAULT 0 NOT NULL,
    BLOQUEADO_HASTA  TIMESTAMP
);

-- ---------------------------------------------------------------------
--  IMPORTACIÓN DE USUARIOS (CSV / Excel)
--  El avance vive aquí para que cualquier réplica de la API lo pueda ver
-- ---------------------------------------------------------------------
CREATE TABLE ESTADOS_IMPORTACION (
    CLAVE        VARCHAR(12)  NOT NULL PRIMARY KEY,   -- PROCESANDO, TERMINADO, ERROR
    DESCRIPCION  VARCHAR(40)  NOT NULL
);

-- Tipos de archivo que se pueden importar: uno por tipo de usuario, o "general"
-- (cada fila trae su tipo: ALUMNO, PROFESOR o ADMIN)
CREATE TABLE TIPOS_IMPORTACION (
    CLAVE        VARCHAR(10)  NOT NULL PRIMARY KEY,   -- alumnos, maestros, admins, general
    DESCRIPCION  VARCHAR(40)  NOT NULL
);

CREATE TABLE IMPORTACIONES (
    ID            CHAR(16) CHARACTER SET OCTETS  NOT NULL PRIMARY KEY,
    TIPO          VARCHAR(10)   NOT NULL,
    ARCHIVO       VARCHAR(255)  NOT NULL,
    ESTADO        VARCHAR(12)   DEFAULT 'PROCESANDO' NOT NULL REFERENCES ESTADOS_IMPORTACION (CLAVE),
    MENSAJE       VARCHAR(300),
    PORCENTAJE    SMALLINT      DEFAULT 0 NOT NULL,
    LEIDAS        INTEGER       DEFAULT 0 NOT NULL,
    INSERTADOS    INTEGER       DEFAULT 0 NOT NULL,
    ACTUALIZADOS  INTEGER       DEFAULT 0 NOT NULL,
    CON_ERROR     INTEGER       DEFAULT 0 NOT NULL,
    ID_USUARIO    CHAR(16) CHARACTER SET OCTETS  REFERENCES USUARIOS (ID) ON DELETE SET NULL,
    INICIO        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ACTUALIZADO   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,   -- latido: si deja de cambiar, la réplica murió
    FIN           TIMESTAMP,
    CONSTRAINT FK_IMPORTACIONES_TIPO FOREIGN KEY (TIPO) REFERENCES TIPOS_IMPORTACION (CLAVE)
);

-- Filas del archivo que no se pudieron importar
CREATE TABLE IMPORTACION_ERRORES (
    ID_IMPORTACION  CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES IMPORTACIONES (ID) ON DELETE CASCADE,
    FILA            INTEGER       NOT NULL,
    MENSAJE         VARCHAR(300)  NOT NULL,
    PRIMARY KEY (ID_IMPORTACION, FILA)
);

-- ---------------------------------------------------------------------
--  LABORATORIOS GNS3 (un contenedor Docker por laboratorio)
--  Cada laboratorio usa un bloque de puertos: el primero es el GNS3 server
--  y los demás son las consolas de los routers/PCs
-- ---------------------------------------------------------------------
CREATE TABLE ESTADOS_LABORATORIO (
    CLAVE        VARCHAR(12)  NOT NULL PRIMARY KEY,   -- CREANDO, CORRIENDO, ERROR
    DESCRIPCION  VARCHAR(40)  NOT NULL
);

CREATE TABLE LABORATORIOS (
    ID             CHAR(16) CHARACTER SET OCTETS  NOT NULL PRIMARY KEY,
    ID_DUENO       CHAR(16) CHARACTER SET OCTETS  NOT NULL UNIQUE REFERENCES USUARIOS (ID) ON DELETE CASCADE,
    CONTENEDOR     VARCHAR(40)   NOT NULL UNIQUE,    -- nombre del contenedor en Docker
    PUERTO_BASE    INTEGER       NOT NULL UNIQUE,    -- puerto del GNS3 server
    CODIGO_EQUIPO  VARCHAR(8)    UNIQUE,             -- NULL = individual
    ESTADO         VARCHAR(12)   DEFAULT 'CREANDO' NOT NULL REFERENCES ESTADOS_LABORATORIO (CLAVE),
    MENSAJE        VARCHAR(300),
    INICIO         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Compañeros que se unieron a un laboratorio de equipo (uno a la vez)
CREATE TABLE LABORATORIO_MIEMBROS (
    ID_LABORATORIO  CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES LABORATORIOS (ID) ON DELETE CASCADE,
    ID_USUARIO      CHAR(16) CHARACTER SET OCTETS  NOT NULL UNIQUE REFERENCES USUARIOS (ID) ON DELETE CASCADE,
    UNIDO           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (ID_LABORATORIO, ID_USUARIO)
);

CREATE TABLE ESTADOS_INVITACION (
    CLAVE        VARCHAR(12)  NOT NULL PRIMARY KEY,   -- PENDIENTE, ACEPTADA, RECHAZADA
    DESCRIPCION  VARCHAR(40)  NOT NULL
);

CREATE TABLE INVITACIONES (
    ID              CHAR(16) CHARACTER SET OCTETS  NOT NULL PRIMARY KEY,
    ID_LABORATORIO  CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES LABORATORIOS (ID) ON DELETE CASCADE,
    ID_EMISOR       CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES USUARIOS (ID) ON DELETE CASCADE,
    ID_RECEPTOR     CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES USUARIOS (ID) ON DELETE CASCADE,
    ESTADO          VARCHAR(12)   DEFAULT 'PENDIENTE' NOT NULL REFERENCES ESTADOS_INVITACION (CLAVE),
    CREADA          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ---------------------------------------------------------------------
--  DESPLIEGUES DE TOPOLOGÍAS (Plantillas del profesor; después, la IA)
--  Corren en segundo plano: aquí se guarda el avance y el resultado.
--  LAB_ACTIVO = ID_LABORATORIO mientras está PROCESANDO y NULL al terminar:
--  su UNIQUE impide 2 despliegues a la vez en el mismo lab, aunque haya
--  2 réplicas de la API (Firebird permite varios NULL en un UNIQUE).
-- ---------------------------------------------------------------------
CREATE TABLE ESTADOS_DESPLIEGUE (
    CLAVE        VARCHAR(12)  NOT NULL PRIMARY KEY,   -- PROCESANDO, TERMINADO, ERROR
    DESCRIPCION  VARCHAR(40)  NOT NULL
);

CREATE TABLE DESPLIEGUES (
    ID              CHAR(16) CHARACTER SET OCTETS  NOT NULL PRIMARY KEY,
    ID_LABORATORIO  CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES LABORATORIOS (ID) ON DELETE CASCADE,
    LAB_ACTIVO      CHAR(16) CHARACTER SET OCTETS  UNIQUE,
    ID_USUARIO      CHAR(16) CHARACTER SET OCTETS  REFERENCES USUARIOS (ID) ON DELETE SET NULL,
    ORIGEN          VARCHAR(20)   NOT NULL,          -- basica, intermedia, avanzada (o "ia")
    PROYECTO        VARCHAR(40)   NOT NULL,          -- nombre del proyecto en GNS3
    ESTADO          VARCHAR(12)   DEFAULT 'PROCESANDO' NOT NULL REFERENCES ESTADOS_DESPLIEGUE (CLAVE),
    PORCENTAJE      SMALLINT      DEFAULT 0 NOT NULL,
    PASO            VARCHAR(120),                    -- lo que está haciendo ahora
    MENSAJE         VARCHAR(1000),                   -- resultado o error
    INICIO          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ACTUALIZADO     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,   -- latido
    FIN             TIMESTAMP
);

-- ---------------------------------------------------------------------
--  PRÁCTICAS CON CALIFICACIÓN, SUPERVISIÓN Y ACCESO A LOS LABS POR IP
--  (mismas tablas que docs/migraciones/003_practicas.sql)
--  SESIONES_IP: la IP de cada sesión web abre el puerto de SU lab y las
--  consolas de los nodos que existen (service/accesos.go).
--  ENTREGAS: PK (práctica, alumno) = una sola entrega por alumno.
--  REVISIONES.LAB_ACTIVO UNIQUE = una sola revisión a la vez por lab.
-- ---------------------------------------------------------------------
CREATE TABLE SESIONES_IP (
    ID_SESION   VARCHAR(64)  NOT NULL PRIMARY KEY,
    ID_USUARIO  CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES USUARIOS (ID) ON DELETE CASCADE,
    IP          VARCHAR(45)  NOT NULL,
    CREADA      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    VISTA       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE SUPERVISIONES_ACTIVAS (
    ID_USUARIO      CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES USUARIOS (ID) ON DELETE CASCADE,
    ID_LABORATORIO  CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES LABORATORIOS (ID) ON DELETE CASCADE,
    HASTA           TIMESTAMP NOT NULL,
    PRIMARY KEY (ID_USUARIO, ID_LABORATORIO)
);

CREATE TABLE SUPERVISIONES (
    ID          CHAR(16) CHARACTER SET OCTETS  NOT NULL PRIMARY KEY,
    ID_USUARIO  CHAR(16) CHARACTER SET OCTETS  REFERENCES USUARIOS (ID) ON DELETE SET NULL,
    ID_ALUMNO   CHAR(16) CHARACTER SET OCTETS  REFERENCES USUARIOS (ID) ON DELETE SET NULL,
    ACCION      VARCHAR(30)   NOT NULL,
    DETALLE     VARCHAR(200),
    FECHA       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Latido de servicios externos a la API (el agente del firewall raccoon-accesos)
-- (docs/migraciones/004_sin_token.sql)
CREATE TABLE LATIDOS (
    SERVICIO  VARCHAR(30)  NOT NULL PRIMARY KEY,
    VISTO     TIMESTAMP    NOT NULL
);

CREATE TABLE ESTADOS_PRACTICA (
    CLAVE        VARCHAR(12)  NOT NULL PRIMARY KEY,
    DESCRIPCION  VARCHAR(40)  NOT NULL
);

CREATE TABLE PRACTICAS (
    ID               CHAR(16) CHARACTER SET OCTETS  NOT NULL PRIMARY KEY,
    ID_PROFESOR      CHAR(16) CHARACTER SET OCTETS  REFERENCES USUARIOS (ID) ON DELETE SET NULL,
    ID_GRUPO         CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES GRUPOS (ID) ON DELETE CASCADE,
    NOMBRE           VARCHAR(80)   NOT NULL,
    INSTRUCCIONES    BLOB SUB_TYPE TEXT,
    PROYECTO_ORIGEN  VARCHAR(100),
    ESTADO           VARCHAR(12)   DEFAULT 'EXPORTANDO' NOT NULL REFERENCES ESTADOS_PRACTICA (CLAVE),
    PASO             VARCHAR(120),
    MENSAJE          VARCHAR(500),
    CREADA           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ACTUALIZADO      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ACTIVADA         TIMESTAMP,
    CERRADA          TIMESTAMP
);

CREATE TABLE PRACTICA_PROYECTOS (
    ID_PRACTICA  CHAR(16) CHARACTER SET OCTETS  NOT NULL PRIMARY KEY REFERENCES PRACTICAS (ID) ON DELETE CASCADE,
    ARCHIVO      BLOB SUB_TYPE BINARY NOT NULL,
    TAMANO       INTEGER NOT NULL
);

CREATE TABLE PRACTICA_NODOS (
    ID_PRACTICA  CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES PRACTICAS (ID) ON DELETE CASCADE,
    NODO         VARCHAR(40)  NOT NULL,
    TIPO_NODO    VARCHAR(20)  NOT NULL,
    PRIMARY KEY (ID_PRACTICA, NODO)
);

CREATE TABLE PRACTICA_PUERTOS (
    ID_PRACTICA  CHAR(16) CHARACTER SET OCTETS  NOT NULL,
    NODO         VARCHAR(40)  NOT NULL,
    PUERTO       VARCHAR(40)  NOT NULL,
    ORDEN        SMALLINT     NOT NULL,
    PRIMARY KEY (ID_PRACTICA, NODO, PUERTO),
    FOREIGN KEY (ID_PRACTICA, NODO) REFERENCES PRACTICA_NODOS (ID_PRACTICA, NODO) ON DELETE CASCADE
);

CREATE TABLE TIPOS_CRITERIO (
    CLAVE        VARCHAR(15)  NOT NULL PRIMARY KEY,
    DESCRIPCION  VARCHAR(60)  NOT NULL
);

CREATE TABLE CRITERIOS (
    ID           CHAR(16) CHARACTER SET OCTETS  NOT NULL PRIMARY KEY,
    ID_PRACTICA  CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES PRACTICAS (ID) ON DELETE CASCADE,
    ORDEN        SMALLINT     NOT NULL,
    TIPO         VARCHAR(15)  NOT NULL REFERENCES TIPOS_CRITERIO (CLAVE),
    PESO         SMALLINT     NOT NULL,
    NODO         VARCHAR(40)  NOT NULL,
    INTERFAZ     VARCHAR(40),
    DESTINO      VARCHAR(40),
    VALOR        VARCHAR(200),
    MODO         VARCHAR(12),
    MENSAJE      VARCHAR(200)
);

CREATE TABLE ESTADOS_REVISION (
    CLAVE        VARCHAR(12)  NOT NULL PRIMARY KEY,
    DESCRIPCION  VARCHAR(40)  NOT NULL
);

CREATE TABLE REVISIONES (
    ID            CHAR(16) CHARACTER SET OCTETS  NOT NULL PRIMARY KEY,
    ID_PRACTICA   CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES PRACTICAS (ID) ON DELETE CASCADE,
    ID_USUARIO    CHAR(16) CHARACTER SET OCTETS  REFERENCES USUARIOS (ID) ON DELETE SET NULL,
    LAB_ACTIVO    CHAR(16) CHARACTER SET OCTETS  UNIQUE,
    ES_PRUEBA     BOOLEAN DEFAULT FALSE NOT NULL,
    ESTADO        VARCHAR(12)  DEFAULT 'EN_COLA' NOT NULL REFERENCES ESTADOS_REVISION (CLAVE),
    PORCENTAJE    SMALLINT     DEFAULT 0 NOT NULL,
    PASO          VARCHAR(120),
    MENSAJE       VARCHAR(500),
    CALIFICACION  SMALLINT,
    INICIO        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ACTUALIZADO   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    FIN           TIMESTAMP
);

CREATE TABLE REVISION_PROYECTO (
    ID_REVISION  CHAR(16) CHARACTER SET OCTETS  NOT NULL PRIMARY KEY REFERENCES REVISIONES (ID) ON DELETE CASCADE,
    ARCHIVO      BLOB SUB_TYPE BINARY NOT NULL,
    TAMANO       INTEGER NOT NULL
);

CREATE TABLE REVISION_CONFIGS (
    ID_REVISION  CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES REVISIONES (ID) ON DELETE CASCADE,
    NODO         VARCHAR(40)  NOT NULL,
    CONFIG       BLOB SUB_TYPE TEXT,
    PRIMARY KEY (ID_REVISION, NODO)
);

CREATE TABLE REVISION_RESULTADOS (
    ID_REVISION  CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES REVISIONES (ID) ON DELETE CASCADE,
    ID_CRITERIO  CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES CRITERIOS (ID) ON DELETE CASCADE,
    CUMPLE       BOOLEAN      NOT NULL,
    PUNTOS       SMALLINT     NOT NULL,
    OBTENIDO     VARCHAR(500),
    PRIMARY KEY (ID_REVISION, ID_CRITERIO)
);

CREATE TABLE ENTREGAS (
    ID_PRACTICA  CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES PRACTICAS (ID) ON DELETE CASCADE,
    ID_USUARIO   CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES USUARIOS (ID) ON DELETE CASCADE,
    ID_REVISION  CHAR(16) CHARACTER SET OCTETS  NOT NULL REFERENCES REVISIONES (ID) ON DELETE CASCADE,
    PRIMARY KEY (ID_PRACTICA, ID_USUARIO)
);

